#[test]
fn changed_expected_tags_or_main_tip_refuse_preparation() {
    let f = Fixture::new(true);
    let tree = f.export();
    git(&f.mirror, &["tag", "unexpected", &f.tip]);
    refused(
        f.prepare(&tree, Some(&f.tip)),
        "expected mirror tags changed",
    );
    fs::write(&f.tags, tag_snapshot(&f.mirror)).unwrap();
    let next = git(
        &f.mirror,
        &[
            "commit-tree",
            &git(&f.mirror, &["rev-parse", "HEAD^{tree}"]),
            "-p",
            &f.tip,
            "-m",
            "Concurrent mirror update",
        ],
    );
    git(&f.mirror, &["update-ref", "refs/heads/main", &next]);
    refused(
        f.prepare(&tree, Some(&f.tip)),
        "expected mirror main tip changed",
    );
}

#[test]
fn generated_mirror_same_source_is_noop_but_different_tree_refuses() {
    let mut f = Fixture::new(true);
    let tree = f.export();
    let v: Value = serde_json::from_str(&output_text(f.prepare(&tree, Some(&f.tip)))).unwrap();
    f.publish_fixture(v["prepared_commit"].as_str().unwrap());
    let value: Value = serde_json::from_str(&output_text(f.prepare(&tree, None))).unwrap();
    assert_eq!(value["no_op"], true);
    assert_eq!(value["prepared_commit"], f.tip);
    let different = f.replace_blob(&tree, "README.md", b"inconsistent generated bytes\n");
    refused(
        f.prepare(&different, None),
        "same source has different export tree or provenance",
    );
}

#[test]
fn subsequent_source_advances_and_older_source_refuses() {
    let mut f = Fixture::new(true);
    let original_source = f.source.clone();
    let first_tree = f.export();
    let v: Value =
        serde_json::from_str(&output_text(f.prepare(&first_tree, Some(&f.tip)))).unwrap();
    f.publish_fixture(v["prepared_commit"].as_str().unwrap());
    f.advance_source();
    let next_tree = f.export();
    let parent = f.tip.clone();
    let next: Value = serde_json::from_str(&output_text(f.prepare(&next_tree, None))).unwrap();
    assert_eq!(
        git(
            &f.root,
            &[
                "show",
                "-s",
                "--format=%P",
                next["prepared_commit"].as_str().unwrap()
            ]
        ),
        parent
    );
    f.publish_fixture(next["prepared_commit"].as_str().unwrap());
    git(
        &f.root,
        &[
            "-c",
            "core.hooksPath=/dev/null",
            "checkout",
            "--quiet",
            "--detach",
            &original_source,
        ],
    );
    f.source = original_source;
    refused(
        f.prepare(&first_tree, None),
        "source must advance the prior source ancestry",
    );
}

#[test]
fn unresolved_or_inconsistent_provenance_refuses() {
    let f = Fixture::new(true);
    let tree = f.export();
    let original: Value = serde_json::from_str(&git(
        &f.root,
        &["show", &format!("{tree}:.jeryu-source.json")],
    ))
    .unwrap();
    for (field, value) in [
        ("lock_regeneration_required", json!(true)),
        ("publication_qualified", json!(true)),
        ("component", json!("jeryu-web")),
        ("original_component_tree", json!("0".repeat(40))),
    ] {
        let mut descriptor = original.clone();
        descriptor[field] = value;
        let bad = f.replace_blob(
            &tree,
            ".jeryu-source.json",
            serde_json::to_string(&descriptor).unwrap().as_bytes(),
        );
        let output = f.prepare(&bad, Some(&f.tip));
        assert_eq!(output.status.code(), Some(1));
        assert!(output.stdout.is_empty());
    }
}

