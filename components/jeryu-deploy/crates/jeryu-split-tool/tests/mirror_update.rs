mod mirror_update_fixture;

use mirror_update_fixture::{Fixture, git, output_text, tag_snapshot};
use serde_json::{Value, json};
use std::{fs, process::Output};

fn refused(output: Output, reason: &str) {
    assert_eq!(output.status.code(), Some(1));
    assert!(output.stdout.is_empty());
    assert!(
        String::from_utf8_lossy(&output.stderr).contains(reason),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
}

#[test]
fn initial_preparation_is_deterministic_and_preserves_existing_history_and_tags() {
    let f = Fixture::new(true);
    let tree = f.export();
    let before_source = git(&f.root, &["show-ref"]);
    let before_mirror = git(&f.mirror, &["show-ref"]);
    let first = output_text(f.prepare(&tree, Some(&f.tip)));
    git(&f.root, &["config", "i18n.commitEncoding", "ISO-8859-1"]);
    git(&f.root, &["config", "log.showSignature", "true"]);
    let second = output_text(f.prepare(&tree, Some(&f.tip)));
    assert_eq!(first, second);
    let value: Value = serde_json::from_str(&first).unwrap();
    let commit = value["prepared_commit"].as_str().unwrap();
    assert_eq!(git(&f.root, &["show", "-s", "--format=%P", commit]), f.tip);
    assert_eq!(
        git(&f.root, &["rev-parse", &format!("{commit}^{{tree}}")]),
        tree
    );
    assert_eq!(
        value["generator_source_blobs"].as_object().unwrap().len(),
        7
    );
    assert_eq!(value["publication_qualified"], false);
    assert_eq!(value["qualification_verified"], false);
    assert_eq!(value["no_op"], false);
    assert_eq!(git(&f.root, &["show-ref"]), before_source);
    assert_eq!(git(&f.mirror, &["show-ref"]), before_mirror);
    assert_eq!(
        fs::read_to_string(&f.tags).unwrap(),
        tag_snapshot(&f.mirror)
    );
    assert!(git(&f.root, &["status", "--porcelain"]).is_empty());
}

