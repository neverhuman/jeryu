use serde::{Deserialize, Serialize};

/// Exhaustive taxonomy of control-plane entities.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Hash)]
#[serde(rename_all = "snake_case")]
pub enum EntityKind {
    Fleet,
    RepoFamily,
    Repo,
    Branch,
    Commit,
    MergeRequest,
    Pipeline,
    PipelineBridge,
    Stage,
    Job,
    RunnerPool,
    RunnerManager,
    Runner,
    Node,
    CacheObject,
    CacheRequest,
    CacheVerdict,
    CacheTaint,
    TestPlan,
    TestCase,
    SelectorMiss,
    Agent,
    AgentSession,
    AgentTask,
    AgentRace,
    Bug,
    BugAttempt,
    GitRefUpdate,
    AdmissionDecision,
    CapabilityIntent,
    CapabilityGrant,
    JankuraiRun,
    JankuraiFinding,
    AerFinding,
    SecurityFinding,
    SecretAuthority,
    ReleaseSecretSet,
    Artifact,
    Signature,
    Sbom,
    ReleaseAttempt,
    ReleaseGate,
    Evidence,
    AuditEvent,
    LlmCall,
    Source,
    Action,
    Project,
    EvidenceCapsule,
    SecretAccess,
    Grant,
    Pool,
    System,
}

