fn write_generated_headers(dir: &str) -> Result<(), Box<dyn std::error::Error>> {
    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("ts") {
            continue;
        }
        let content = std::fs::read_to_string(&path)?;
        if content.starts_with(GENERATED_TS_HEADER) {
            continue;
        }
        std::fs::write(&path, format!("{GENERATED_TS_HEADER}{content}"))?;
    }
    Ok(())
}
